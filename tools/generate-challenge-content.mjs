import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { V4_CONTENT_VERSION } from '../src/prototype/progress-v4.js';
import { v4Levels } from '../src/prototype/levels-v4.js';
import { createV4State } from '../src/prototype/model-v4.js';
import { spawnInterval } from '../src/prototype/difficulty.js';
import { DAILY_RULES, DAILY_PRESET_ID } from '../src/prototype/daily-rules.js';

const root = fileURLToPath(new URL('../', import.meta.url));
export const CHALLENGE_SOURCE_FILES = Object.freeze([
  'src/game/hex.js',
  'src/prototype/daily-rules.js',
  'src/prototype/difficulty.js',
  'src/prototype/levels-v4.js',
  'src/prototype/magnet-influence.js',
  'src/prototype/magnet-radius.js',
  'src/prototype/model-v4.js',
  'src/prototype/model.js'
]);
const hash = value => createHash('sha256').update(value).digest('hex');
export function canonicalJSON(value) {
  if (Array.isArray(value)) return '[' + value.map(canonicalJSON).join(',') + ']';
  if (value !== null && typeof value === 'object')
    return '{' + Object.keys(value).sort().map(key => JSON.stringify(key) + ':' + canonicalJSON(value[key])).join(',') + '}';
  return JSON.stringify(value);
}
export function challengeManifest() {
  return {
    schema: 1,
    contentVersion: V4_CONTENT_VERSION,
    profiles: [
      { id: 'campaign-a-v1', goals: v4Levels.map(level => createV4State(level, 0).goal),
        spawnIntervals: v4Levels.map(level => spawnInterval(level.number)) },
      { id: DAILY_PRESET_ID, goals: v4Levels.map(level => DAILY_RULES.createV4State(level, 0).goal),
        spawnIntervals: v4Levels.map(level => DAILY_RULES.spawnInterval(level.number)) }
    ],
    levels: v4Levels.map(level => ({ id: level.id, number: level.number,
      blockers: level.blockers.map(({ col, row }) => ({ col, row })) })),
    sourceSha256: Object.fromEntries(CHALLENGE_SOURCE_FILES.map(file => [file,
      hash(fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n?/g, '\n'))]))
  };
}
export function challengeContentSource() {
  const manifest = challengeManifest(), rulesHash = hash(canonicalJSON(manifest));
  return '// Generated by tools/generate-challenge-content.mjs --write. Do not edit.\n' +
    `export const CONTENT_VERSION = ${JSON.stringify(manifest.contentVersion)};\n` +
    `export const CAMPAIGN_PRESET_ID = ${JSON.stringify(manifest.profiles[0].id)};\n` +
    `export const SHORT_PRESET_ID = ${JSON.stringify(manifest.profiles[1].id)};\n` +
    `export const CHALLENGE_RULES_HASH = ${JSON.stringify(rulesHash)};\n` +
    'const freeze = value => { if (value && typeof value === \'object\') { Object.values(value).forEach(freeze); Object.freeze(value); } return value; };\n' +
    `export const CHALLENGE_MANIFEST = freeze(${JSON.stringify(manifest, null, 2)});\n`;
}
function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || args.some(arg => !['--check', '--write'].includes(arg)))
    throw Error('Usage: node tools/generate-challenge-content.mjs [--check|--write]');
  const target = path.join(root, 'src/prototype/challenge-content-v4.js'), source = challengeContentSource();
  if (args.includes('--write')) fs.writeFileSync(target, source);
  else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n?/g, '\n') !== source)
    throw Error('Challenge content manifest is stale. Review rule changes, then run --write explicitly.');
  const manifest = challengeManifest();
  console.log('PASS challenge content ' + hash(canonicalJSON(manifest)) + '; ' + manifest.levels.length + ' layouts, ' + manifest.profiles.length + ' profiles, ' + CHALLENGE_SOURCE_FILES.length + ' normalized-LF sources.');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
